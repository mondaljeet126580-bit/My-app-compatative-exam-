create or replace function public.chatlink_dispatch_push_outbox()
returns trigger language plpgsql security definer set search_path=''
as $function$
declare v_secret text;
begin
  select decrypted_secret into v_secret from vault.decrypted_secrets where name='chat-push-webhook-secret' limit 1;
  if v_secret is null then
    update public.chat_push_outbox set last_error='Webhook secret is missing from Vault',updated_at=now() where id=new.id;
    return new;
  end if;
  perform net.http_post(
    url:='https://mtitrkspgoqaqdeiluud.supabase.co/functions/v1/chat-push',
    headers:=jsonb_build_object('Content-Type','application/json','apikey','sb_publishable_MNm-dTK29hrtVkiyLRkLIw_qbtbxJu_','x-chat-push-secret',v_secret),
    body:=jsonb_build_object('outbox_id',new.id),
    timeout_milliseconds:=3000
  );
  return new;
end;
$function$;
revoke all on function public.chatlink_dispatch_push_outbox() from public,anon,authenticated;
drop trigger if exists chatlink_dispatch_push_outbox on public.chat_push_outbox;
create trigger chatlink_dispatch_push_outbox after insert on public.chat_push_outbox
for each row execute function public.chatlink_dispatch_push_outbox();
